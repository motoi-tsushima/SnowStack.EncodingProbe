<#
.SYNOPSIS
    CSV の列名の比較に使う対応表（SnowStack.EncodingProbe.PowerShell\Internal\CsvNameCaseTable.cs）を生成する。

.DESCRIPTION
    1.3.0 第六次（BUG-0020）。Import-ProbedCsv の列名の重複の検査や Export-ProbedCsv -Append の列の照合を、
    PowerShell 5.1 でも 7.x（.NET 10）の StringComparison.OrdinalIgnoreCase と同じ結果にするための表を作る。

    .NET 10 の OrdinalIgnoreCase は、UTF-16 の長さが同じ文字列を、符号位置ごと（サロゲートペアは 1 つの符号位置）に
    大文字にそろえて比べる。そこで、すべての符号位置（U+0000〜U+10FFFF。単独のサロゲートも 1 文字として含める）を
    1 文字の文字列にして StringComparer.OrdinalIgnoreCase で並べ、隣り合って等しいものを同値類にまとめる。
    同値類の代表は最小の符号位置とし、代表と違う符号位置だけを「符号位置 → 代表」の組として書き出す。

    必ず PowerShell 7.x（.NET 10）で実行すること。.NET の版が上がって結果が変わったら、表を作り直して
    CsvNameComparerTests（net10.0 で、表と実行環境の OrdinalIgnoreCase が全符号位置で一致することを確かめる）を通す。

.EXAMPLE
    pwsh -NoProfile -File tools/New-CsvNameCaseTable.ps1
#>
[CmdletBinding()]
param(
    [string]$OutFile = (Join-Path $PSScriptRoot '..\SnowStack.EncodingProbe.PowerShell\Internal\CsvNameCaseTable.cs')
)

$ErrorActionPreference = 'Stop'

if ($PSVersionTable.PSEdition -ne 'Core' -or [Environment]::Version.Major -lt 10) {
    throw 'PowerShell 7.x（.NET 10 以降）で実行してください。'
}

$all = New-Object System.Collections.Generic.List[string] 1114112
for ($cp = 0; $cp -le 0x10FFFF; $cp++) {
    if ($cp -ge 0xD800 -and $cp -le 0xDFFF) {
        $all.Add([string][char]$cp)   # 単独のサロゲート
    }
    else {
        $all.Add([char]::ConvertFromUtf32($cp))
    }
}

$sorted = $all.ToArray()
[Array]::Sort($sorted, [StringComparer]::OrdinalIgnoreCase)

function Get-CodePoint([string]$s) {
    if ($s.Length -eq 2) { return [char]::ConvertToUtf32($s[0], $s[1]) }
    return [int]$s[0]
}

$pairs = New-Object System.Collections.Generic.List[int[]]
$classes = 0
$i = 0
while ($i -lt $sorted.Length) {
    $j = $i + 1
    while ($j -lt $sorted.Length -and [string]::Equals($sorted[$i], $sorted[$j], [StringComparison]::OrdinalIgnoreCase)) { $j++ }

    if ($j - $i -gt 1) {
        $classes++
        $members = @($sorted[$i..($j - 1)] | ForEach-Object { Get-CodePoint $_ } | Sort-Object)
        $lengths = @($sorted[$i..($j - 1)] | ForEach-Object { $_.Length } | Sort-Object -Unique)
        if ($lengths.Count -ne 1) { throw "UTF-16 の長さが違う符号位置が同じ同値類にある: $($members -join ',')" }

        $representative = $members[0]
        foreach ($m in $members[1..($members.Count - 1)]) { $pairs.Add([int[]]@($m, $representative)) }
    }

    $i = $j
}

$ordered = $pairs | Sort-Object { $_[0] }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('// tools/New-CsvNameCaseTable.ps1 が生成した。手で直さないこと。')
[void]$sb.AppendLine("// 生成した実行環境: $([Runtime.InteropServices.RuntimeInformation]::FrameworkDescription)")
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace SnowStack.EncodingProbe.PowerShell.Internal')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>')
[void]$sb.AppendLine('    /// .NET 10 の StringComparison.OrdinalIgnoreCase の同値類（1.3.0 第六次。BUG-0020）。<see cref="CsvNameComparer"/> が使う。')
[void]$sb.AppendLine('    /// </summary>')
[void]$sb.AppendLine('    internal static class CsvNameCaseTable')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        /// <summary>表を生成した .NET の版</summary>')
[void]$sb.AppendLine(('        internal const string RuntimeVersion = "{0}";' -f [Environment]::Version))
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('        /// <summary>同値類の数（2 個以上の符号位置を持つもの）</summary>'))
[void]$sb.AppendLine(('        internal const int ClassCount = {0};' -f $classes))
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        /// <summary>')
[void]$sb.AppendLine('        /// 「符号位置, 同値類の代表（最小の符号位置）」の組を、符号位置の昇順に並べたもの。代表と同じ符号位置は含めない。')
[void]$sb.AppendLine('        /// </summary>')
[void]$sb.AppendLine('        internal static readonly int[] Pairs =')
[void]$sb.AppendLine('        {')
$line = New-Object System.Text.StringBuilder
$n = 0
foreach ($p in $ordered) {
    [void]$line.Append(('0x{0:X4}, 0x{1:X4}, ' -f $p[0], $p[1]))
    $n++
    if ($n % 6 -eq 0) { [void]$sb.AppendLine('            ' + $line.ToString().TrimEnd()); [void]$line.Clear() }
}
if ($line.Length -gt 0) { [void]$sb.AppendLine('            ' + $line.ToString().TrimEnd()) }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutFile), $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))
"同値類 {0} 個、組 {1} 個を {2} に書き出した" -f $classes, $ordered.Count, $OutFile
